"""Print one example of each kind of data we have, for a quick look."""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'credit'))
import config  # noqa: E402
from webshop_env import DATA_DIR, make_env  # noqa: E402


def short(v, n=160):
    s = json.dumps(v, ensure_ascii=False) if not isinstance(v, str) else v
    return s if len(s) <= n else s[:n] + f'... ({len(s)} chars)'


def section(title):
    print(f'\n######## {title}')


products = json.load(open(os.path.join(DATA_DIR, 'items_shuffle_1000.json')))
attrs = json.load(open(os.path.join(DATA_DIR, 'items_ins_v2_1000.json')))
trajs = [json.loads(l) for l in open(sys.argv[1] if len(sys.argv) > 1 else config.runs_dir('determinism_100', 'trajectories.jsonl'))]

env = make_env()
goals = env.server.goals

# Trajectory to show: partial reward, reasonably long, visits an item page.
pick = next(t for t in trajs
            if 0 < t['steps'][-1].get('reward', 0) < 1 and len(t['actions']) >= 5)
goal = goals[pick['idx']]

section('A. product record (items_shuffle_1000.json), 1 of %d' % len(products))
p = next(p for p in products if p['asin'] == goal['asin']) if any(
    p['asin'] == goal['asin'] for p in products) else products[0]
for k, v in p.items():
    print(f'  {k:16s} {short(v)}')

section('B. product attributes (items_ins_v2_1000.json), same product')
print(' ', short(attrs.get(p['asin']), 400))

section('C. task / goal (generated by the env), %d goals in total' % len(goals))
for k, v in goal.items():
    print(f'  {k:16s} {short(v, 200)}')

section('D. one trajectory, replayed from the logged actions (goal idx %d)' % pick['idx'])
obs, _ = env.reset(session=pick['idx'])
print(f'[s0] page text:\n  {obs}')
for t, a in enumerate(pick['actions'], 1):
    obs, reward, done, _ = env.step(a)
    print(f'\n--> action {t}: {a}')
    if done:
        print(f'    DONE, reward = {reward:.3f}')
        info = env.server.user_sessions[str(pick["idx"])].get('verbose_info', {})
        print('    reward breakdown:', short({k: v for k, v in info.items()
                                               if not isinstance(v, (list, dict))}, 600))
    else:
        print(f'[s{t}] page text:\n  {short(obs, 700)}')
        print(f'    admissible clicks: {short(env.get_available_actions()["clickables"], 300)}')

section('E. what we stored for that trajectory (runs/determinism_100/trajectories.jsonl)')
rec = dict(pick)
rec['steps'] = rec['steps'][:2] + ['...']
print(' ', short(rec, 1200))

section('F. random-policy run over 100 tasks')
lens = collections.Counter(len(t['actions']) for t in trajs)
rews = [t['steps'][-1].get('reward', 0) for t in trajs]
print('  trajectory length -> count:', dict(sorted(lens.items())))
bins = collections.Counter('0' if r == 0 else '1.0' if r == 1 else '(0,0.5)' if r < 0.5 else '[0.5,1)'
                           for r in rews)
print('  final reward bins:', dict(bins), ' (no buy within 15 steps counts as 0)')
